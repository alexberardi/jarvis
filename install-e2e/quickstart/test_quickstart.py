"""Regression suite for the SOURCE-DEV quickstart path.

Every test here maps to a real failure found on 2026-09-01, when the quickstart
was run on a clean machine for the first time in months. None of them are
hypothetical, and none are covered by install-e2e.yml — that suite stands up the
installer's prebuilt-image artifact, so it cannot see anything that breaks in
``clone-repos.sh``, ``./jarvis init``, ``_stamp_env_files`` or ``_auto_register``.

Phase ordering mirrors what a contributor does:
    A. clone   — the repo inventory is complete and actually clones
    B. init    — succeeds on a CLEAN machine (no pre-existing docker network)
    C. start   — every service comes up
    D. wiring  — the cross-service invariants that were silently broken
    E. gpu     — the model really loaded on the GPU (source-built CUDA wheels)
"""
from __future__ import annotations

import json
import re
import subprocess

import pytest
import requests

from conftest import (
    HTTP_SERVICES,
    KNOWN_BROKEN,
    BASE_URL,
    env_values,
    http_status,
    result_lines,
    result_rc,
    result_text,
    secret_state,
)


# ── Phase A: clone ───────────────────────────────────────────────────────────
def test_clone_repos_inventory_is_complete() -> None:
    """Every service ./jarvis expects must have a clone source.

    FOUND 2026-09-01: clone-repos.sh omitted jarvis-notifications and
    jarvis-web entirely, so a fresh checkout could never start a full stack —
    ./jarvis start --all just skipped them (the loop `continue`s on a missing
    directory, so it fails silently rather than loudly).
    """
    omitted = result_lines("clone_omitted_by_script")
    assert not omitted, (
        "services in the ./jarvis SERVICES registry with no entry in "
        f"scripts/clone-repos.sh: {omitted}"
    )


def test_all_listed_repos_clone_successfully() -> None:
    """Every repo clone-repos.sh lists must actually exist and clone.

    FOUND 2026-09-01: the script lists jarvis-mcp-client, which does not exist
    on GitHub. Under the script's `set -e` that aborted the whole run at that
    point, so the ~8 repos listed after it were never cloned — and the script
    still printed its earlier progress, so it read as a partial success.
    """
    failures = result_lines("clone_failures")
    assert not failures, f"repos listed in clone-repos.sh that failed to clone: {failures}"


# ── Phase B: init ────────────────────────────────────────────────────────────
def test_init_succeeds_on_clean_machine() -> None:
    """./jarvis init must work on a box that has never run jarvis.

    FOUND 2026-09-01: `_write_network_override` — the ONLY caller of
    `docker network create jarvis-net` — runs from cmd_start, never cmd_init.
    But init's `_start_infra` brings up jarvis-data-services, whose compose
    declares jarvis-net as `external: true`. So init died with "network
    jarvis-net declared as external, but could not be found" on every clean
    machine, and could only succeed AFTER a start --all that itself needs init.
    """
    rc = result_rc("phase_init.rc")
    assert rc is not None, "init phase never ran"
    log = result_text("init.log")
    if rc != 0 and "declared as external" in log:
        pytest.fail(
            "./jarvis init failed on the jarvis-net chicken-and-egg: the network "
            "is only created by cmd_start.\n"
            + "\n".join(log.splitlines()[-15:])
        )
    assert rc == 0, "./jarvis init failed:\n" + "\n".join(log.splitlines()[-25:])


def test_init_generates_every_required_token() -> None:
    """tokens.env must carry every shared secret a service fails closed without.

    FOUND 2026-09-01: JARVIS_ADAPTER_CALLBACK_TOKEN was never generated by
    _generate_tokens nor stamped by _stamp_env_files. command-center logged
    "async-job callbacks will be REJECTED (503)" at every startup, so deep
    research, memory extraction, transcript mark_processed and inbox delivery
    all completed in the worker and then silently persisted nothing.
    """
    tokens = result_text("tokens.env")
    assert tokens, "no ~/.jarvis/tokens.env captured — init did not get that far"
    required = [
        "AUTH_SECRET_KEY",
        "JARVIS_AUTH_ADMIN_TOKEN",
        "JARVIS_CONFIG_ADMIN_TOKEN",
        "ADMIN_API_KEY",
        "MODEL_SERVICE_TOKEN",
        "JARVIS_ADAPTER_CALLBACK_TOKEN",
    ]
    missing = [k for k in required if not re.search(rf"^{k}=.+$", tokens, re.M)]
    assert not missing, f"tokens.env missing required secrets: {missing}"


