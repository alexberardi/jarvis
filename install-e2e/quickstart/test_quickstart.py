# ── Phase D: cross-service wiring ────────────────────────────────────────────
@pytest.mark.parametrize(
    "service",
    ["jarvis-command-center", "jarvis-llm-proxy-api", "jarvis-tts", "jarvis-whisper-api"],
)
def test_app_keys_are_minted(service: str) -> None:
    """App-to-app credentials must be real, not empty or placeholders.

    FOUND 2026-09-01: _auto_register reported "Registered 12 services (all
    credentials up to date)" while every JARVIS_APP_KEY was empty and
    jarvis-tts still held the literal CHANGE_ME_get_from_jarvis_auth_admin.
    Registration had actually failed (auth_ok=false) but the summary line only
    counts .env writes, so a total failure printed as success.
    """
    env = env_values(service)
    state = secret_state(env.get("JARVIS_APP_KEY"))
    assert state == "set", (
        f"{service} JARVIS_APP_KEY is {state} "
        f"({env.get('JARVIS_APP_KEY')!r}) — app-to-app auth will 401"
    )


def test_service_registration_reaches_auth() -> None:
    """config-service must be able to reach jarvis-auth to mint app keys.

    FOUND 2026-09-01: in bridge mode every service was registered at
    host:localhost + published port, and config-service's JARVIS_AUTH_URL was
    host.docker.internal:7701. A container on jarvis-net dialling a published
    port that DNATs back into jarvis-net dies on NAT hairpin, so the auth leg
    silently failed: `{"auth_ok": false, "error": "Auth service error: "}` —
    an empty error string, because the httpx exception was swallowed.
    """
    token = None
    for line in result_text("env.jarvis-config-service").splitlines():
        if line.startswith("JARVIS_AUTH_ADMIN_TOKEN="):
            token = line.partition("=")[2]
    if token is None or token.startswith("<empty"):
        pytest.skip("no admin token captured; covered by test_init_generates_every_required_token")

    # Re-registering an existing service is idempotent — we assert the auth leg,
    # not creation. The token value itself is redacted in artifacts, so read it
    # from the live stack instead.
    admin = subprocess.run(
        ["docker", "exec", "jarvis-config-service-jarvis-config-1",
         "printenv", "JARVIS_AUTH_ADMIN_TOKEN"],
        capture_output=True, text=True,
    )
    if admin.returncode != 0 or not admin.stdout.strip():
        pytest.skip("could not read admin token from the running container")

    r = requests.post(
        f"{BASE_URL}:7700/v1/services/register",
        headers={"X-Jarvis-Admin-Token": admin.stdout.strip()},
        json={"services": [{"name": "jarvis-command-center", "host": "jarvis-voice-api",
                            "port": 7703, "external_host": "localhost", "external_port": 7703}]},
        timeout=30,
    )
    assert r.status_code == 200, f"register returned {r.status_code}: {r.text[:200]}"
    result = r.json()["results"][0]
    assert result["auth_ok"] is True, (
        "config-service could not reach jarvis-auth — app keys cannot be minted. "
        f"error={result.get('error')!r}"
    )


def test_url_styles_resolve_for_each_consumer_class() -> None:
    """Each consumer class must get an address it can actually reach.

    In bridge mode host/port are CONTAINER coords and external_host/external_port
    the published ones (see jarvis-config-service/app/models.py). The three
    styles must therefore differ in the right direction — a Pi on the LAN and a
    container on jarvis-net cannot use the same URL.
    """
    def url_for(style: str, name: str = "jarvis-auth", **params) -> str | None:
        r = requests.get(f"{BASE_URL}:7700/services", params={"style": style, **params}, timeout=15)
        r.raise_for_status()
        for s in r.json()["services"]:
            if s["name"] == name:
                return s.get("url")
        return None

    default = url_for("default")
    external = url_for("external")
    remote = url_for("remote", remote_host="10.99.99.99")

    assert default, "jarvis-auth not registered"
    # In-stack callers must NOT be handed a loopback address.
    assert "localhost" not in default and "127.0.0.1" not in default, (
        f"style=default returned {default!r} — a container cannot reach that"
    )
    # Off-network clients (mobile) must get the published port, not container DNS.
    assert external and ("localhost" in external or "127.0.0.1" in external), (
        f"style=external returned {external!r} — off-docker clients need published coords"
    )
    # Another machine must get ITS reachable host, not a container name.
    assert remote and "10.99.99.99" in remote, (
        f"style=remote returned {remote!r} — remote_host rewrite did not apply, so "
        "distributed installs (a Pi node, a second host) get an unreachable URL"
    )


